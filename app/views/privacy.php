    <h3>Cosa viene raccolto</h3>
    <p>
      <strong>I log del server.</strong> Come su qualunque sito, il server
      annota ogni richiesta che riceve: indirizzo IP, data e ora, pagina
      richiesta, tipo di browser e pagina di provenienza. Servono a far
      funzionare il sito, a capire cosa si rompe e a difenderlo dagli
      abusi. La base giuridica è il legittimo interesse (art. 6.1.f del
      Regolamento). I log sono tenuti dal fornitore dell'hosting sui suoi
      server in Italia, e cancellati automaticamente dopo pochi giorni.
    </p>
    <p>
      <strong>Nient'altro.</strong> Non ci sono strumenti di statistica,
      non c'è registrazione, non ci sono moduli di contatto, non c'è
      newsletter. Quello che scrivi nel campo di ricerca viene usato per
      cercare e finisce nei log del server come qualunque altro indirizzo
      richiesto; non viene salvato da nessun'altra parte.
    </p>

    <h3>Cookie</h3>
    <p>
      Nessuno, per chi legge. Il pannello di amministrazione — che riguarda
      solo chi gestisce il sito — usa un cookie tecnico di sessione, che
      esiste soltanto dopo aver fatto l'accesso ed è esente da consenso.
    </p>

    <h3>Servizi di altri</h3>
    <p>
      Nessuno che si carichi da solo. In particolare i caratteri tipografici
      sono ospitati su questo server e non su Google Fonts, e le fotografie
      sono copiate qui e non richiamate da Wikimedia: aprendo una pagina, il
      tuo browser non contatta nessun server diverso da deftones.it.
    </p>
    <p>
      Ci sono invece <em>collegamenti</em> verso siti esterni: le fonti
      degli articoli, i profili Facebook e Instagram, le pagine delle
      licenze delle fotografie. Si aprono solo se ci clicchi, e da quel
      momento in poi vale la privacy di quei siti, non questa.
    </p>
    <p>
      <strong>I video.</strong> Diversi articoli dell'archivio contengono
      video di YouTube. Non vengono caricati insieme alla pagina: al loro
      posto trovi un riquadro nero con un pulsante, e finché non lo premi
      nessuna richiesta parte verso Google. Quando lo premi, il video
      arriva da <em>youtube-nocookie.com</em> e da quel momento YouTube
      vede il tuo indirizzo IP: è una tua scelta, fatta con un gesto.
    </p>

